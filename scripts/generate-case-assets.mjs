import { readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";

const root = path.resolve("knowledge-base/cases");
const output = path.resolve("lib/case-assets.generated.ts");

function scalar(value = "") {
  const text = value.trim().replace(/^['"]|['"]$/g, "");
  if (/^-?\d+(\.\d+)?$/.test(text)) return Number(text);
  if (text === "true" || text === "false") return text === "true";
  return text;
}

function parseFrontmatter(markdown) {
  const match = markdown.match(/^---\r?\n([\s\S]*?)\r?\n---\r?\n?([\s\S]*)$/);
  if (!match) throw new Error("case.md 缺少 Frontmatter");
  const data = {};
  for (const line of match[1].split(/\r?\n/)) {
    const separator = line.indexOf(":");
    if (separator < 0) continue;
    data[line.slice(0, separator).trim()] = scalar(line.slice(separator + 1));
  }
  return { data, body: match[2].trim() };
}

const directories = await readdir(root, { withFileTypes: true });
const assets = [];
for (const directory of directories.filter((item) => item.isDirectory())) {
  const casePath = path.join(root, directory.name, "case.md");
  const markdown = await readFile(casePath, "utf8");
  const { data, body } = parseFrontmatter(markdown);
  const imageDirectory = path.join(root, directory.name, "images");
  const sourcePath = path.join(root, directory.name, "sources", "source.md");
  let imageCount = 0;
  let sourceCount = 0;
  try { imageCount = (await readdir(imageDirectory, { withFileTypes: true })).filter((item) => item.isFile()).length; } catch {}
  try { sourceCount = (await readFile(sourcePath, "utf8")).split(/\r?\n/).filter((line) => /^\d+[.)]\s/.test(line.trim())).length; } catch {}
  const tags = String(data.tags || "").split(",").map((item) => item.trim()).filter(Boolean);
  assets.push({
    id: String(data.id || directory.name), slug: String(data.slug || directory.name), title: String(data.title || directory.name),
    province: String(data.province || "待确认"), city: String(data.city || "待确认"), district: data.district ? String(data.district) : undefined,
    category: String(data.category || "城市治理"), year: Number(data.year || new Date().getFullYear()), owner: String(data.owner || "待核验"),
    locationLevel: String(data.location_level || "市级"), lng: Number(data.longitude), lat: Number(data.latitude),
    locationConfidence: Number(data.location_confidence || 0), coverageType: String(data.coverage_type || "单点项目"),
    status: data.content_status === "published" ? "已发布" : "草稿", sourceType: String(data.source_type || "研究报告"),
    evidenceLevel: String(data.evidence_level || "弱"), summary: String(data.summary || ""), painPoints: [], solution: [], outcomes: [],
    aiTags: tags, expertView: "", sourceNote: `由 knowledge-base/cases/${directory.name}/case.md 生成。`, researchReport: body,
    asset: { contentStatus: data.content_status === "published" ? "published" : "candidate", casePath: casePath.replace(path.resolve("."), "").replace(/^[/\\]/, "").replaceAll("\\", "/"), imageCount, sourceCount, poiStatus: data.poi_status === "verified" ? "verified" : "pending", lastVerifiedAt: String(data.last_verified_at || "") },
  });
}

await writeFile(output, `// Generated by scripts/generate-case-assets.mjs. Do not edit.\nimport type { SmartCityCase } from "./case-model";\nexport const caseAssets = ${JSON.stringify(assets, null, 2)} as SmartCityCase[];\n`, "utf8");
console.log(`Generated ${assets.length} case asset(s).`);
